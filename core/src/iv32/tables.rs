/// Expand a 2-pixel packed 16-bit delta `(a, b)` into the 4-pixel mode-10
/// packed 32-bit delta `(a, a, b, b)` preserving signed two's-complement borrows.
#[inline]
pub(super) const fn delta_m10(d: u16) -> u32 {
    let d0 = d as i8 as i32;
    let d1 = (d.wrapping_sub(d0 as u16) >> 8) as i8 as i32;
    (d1 << 24)
        .wrapping_add(d1 << 16)
        .wrapping_add(d0 << 8)
        .wrapping_add(d0) as u32
}

